#!/usr/bin/env node
// Renders `resources/companion/hooks/lib/secret-rules.gen.ts` from the ONE source of the wire
// redaction's rules, `resources/companion/secret-rules.json` (T455 spec §5.5 rule 2, "Drift").
// The source is a copy of T450's deterministic rules (its `from` block names the commit) and lives
// with the companion until T450 lands and adopts it. Every mod that stages the rules carries the
// rendered module byte for byte; `tests/companion/secret-rules-staged.test.ts` pins that.
//
// Usage: node scripts/ci/render-secret-rules.mjs          rewrite the module
//        node scripts/ci/render-secret-rules.mjs --check  exit 1 when the module is stale

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ID = /^[a-z][a-z0-9-]*$/

/**
 * @param {{ from: { branch: string, commit: string, sameAt?: string, table: string, code: string },
 *   rules: { id: string, source: string, flags: string, group?: number, needs?: string[] }[],
 *   placeholderValue: { source: string, flags: string } }} src
 */
export function renderSecretRules(src) {
  const ids = new Set()
  for (const r of src.rules) {
    if (!ID.test(r.id) || ids.has(r.id)) throw new Error(`bad or repeated rule id: ${r.id}`)
    ids.add(r.id)
    new RegExp(r.source, r.flags) // a source that does not compile never reaches a mod
  }
  new RegExp(src.placeholderValue.source, src.placeholderValue.flags)
  const f = src.from
  const lines = [
    '// GENERATED by scripts/ci/render-secret-rules.mjs from resources/companion/secret-rules.json.',
    '// Never edit by hand: change the source and run the script.',
    '//',
    `// T450's deterministic secret rules, ${f.table}, as written in ${f.code},`,
    `// copied from branch ${f.branch} at commit ${f.commit}` +
      (f.sameAt ? ` (identical at ${f.sameAt}).` : '.'),
    '// Plain data, so every mod that stages it carries the same bytes; `redact-wire.ts` compiles it.',
    '',
    'export interface SecretRuleData {',
    '  id: string',
    '  source: string',
    '  flags: string',
    '  /** The capture group that holds the secret; absent: the whole match. */',
    '  group?: number',
    '  /** What the captured value must hold to count (T450: a digit and a letter). */',
    "  needs?: readonly ('digit' | 'letter')[]",
    '}',
    '',
    '// prettier-ignore',
    `export const SECRET_RULES_COMMIT = ${JSON.stringify(f.commit)}`,
    '',
    '// prettier-ignore',
    'export const SECRET_RULES: readonly SecretRuleData[] = ['
  ]
  src.rules.forEach((r, i) => {
    const o = { id: r.id, source: r.source, flags: r.flags }
    if (r.group !== undefined) o.group = r.group
    if (r.needs !== undefined) o.needs = r.needs
    lines.push(`  ${JSON.stringify(o)}${i < src.rules.length - 1 ? ',' : ''}`)
  })
  lines.push(']', '')
  lines.push('/** A captured value this shape is a placeholder, never a secret. */')
  lines.push('// prettier-ignore')
  lines.push(
    `export const PLACEHOLDER_VALUE: { source: string; flags: string } = ${JSON.stringify({
      source: src.placeholderValue.source,
      flags: src.placeholderValue.flags
    })}`
  )
  return lines.join('\n') + '\n'
}

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const SOURCE = join(ROOT, 'resources', 'companion', 'secret-rules.json')
const TARGET = join(ROOT, 'resources', 'companion', 'hooks', 'lib', 'secret-rules.gen.ts')

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const body = renderSecretRules(JSON.parse(await readFile(SOURCE, 'utf8')))
  if (process.argv.includes('--check')) {
    const have = await readFile(TARGET, 'utf8').catch(() => '')
    if (have !== body) {
      console.error('secret-rules.gen.ts is stale: run node scripts/ci/render-secret-rules.mjs')
      process.exit(1)
    }
  } else {
    await writeFile(TARGET, body)
  }
}
