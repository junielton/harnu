#!/usr/bin/env node
// Generate THIRD-PARTY-NOTICES.md: the license text of every third-party package
// and asset that ships inside the packaged app.
//
// What ships: the `dependencies` of package.json (main/preload resolve them from the
// asar at runtime, and the renderer bundles them), plus the renderer-only packages
// Vite bundles from `devDependencies` (BUNDLED_DEV_DEPS), each with its transitive
// runtime dependencies. Build tools that leave nothing in the output are excluded.
// Electron's own notices (LICENSE.electron.txt, LICENSES.chromium.html) are added by
// electron-builder next to the binary.
//
// Usage: node scripts/gen-third-party-notices.mjs   (rewrites the file in place)

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))

/** devDependencies whose code ends up in the renderer bundle. */
export const BUNDLED_DEV_DEPS = ['vue', 'tailwindcss']

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.|-|$)/i

/** Node's resolution order: the nearest `node_modules/<name>` walking up from `fromDir`. */
function pkgDir(name, fromDir) {
  let dir = fromDir
  for (;;) {
    const cand = join(dir, 'node_modules', name)
    if (existsSync(join(cand, 'package.json'))) return cand
    const up = dirname(dir)
    if (up === dir) return null
    dir = up
  }
}

function collect() {
  const seen = new Map() // key name@version -> entry
  const queue = [...Object.keys(pkg.dependencies), ...BUNDLED_DEV_DEPS].map((n) => [n, ROOT])
  while (queue.length) {
    const [name, from] = queue.shift()
    const dir = pkgDir(name, from)
    if (!dir) continue
    const meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    const key = `${meta.name}@${meta.version}`
    if (seen.has(key)) continue
    const files = readdirSync(dir)
      .filter((f) => LICENSE_FILE.test(f))
      .sort()
    const text = files.map((f) => readFileSync(join(dir, f), 'utf8').trim()).join('\n\n')
    const repo = typeof meta.repository === 'string' ? meta.repository : meta.repository?.url
    seen.set(key, {
      name: meta.name,
      version: meta.version,
      license: typeof meta.license === 'string' ? meta.license : meta.license?.type || 'UNKNOWN',
      repo: repo ? repo.replace(/^git\+/, '').replace(/\.git$/, '') : '',
      text
    })
    for (const dep of Object.keys(meta.dependencies || {})) queue.push([dep, dir])
    for (const dep of Object.keys(meta.optionalDependencies || {})) queue.push([dep, dir])
  }
  return [...seen.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
  )
}

function fence(text) {
  return '```text\n' + text.replace(/```/g, "'''") + '\n```'
}

function render(entries) {
  const fonts = join(ROOT, 'src/renderer/src/assets/fonts')
  const out = [
    '# Third-party notices',
    '',
    'Harnu is MIT-licensed (see `LICENSE`). The packaged app also contains the third-party',
    'software and assets listed below, each under its own license. This file is generated by',
    '`scripts/gen-third-party-notices.mjs`; do not edit it by hand.',
    '',
    'Electron and Chromium ship their own notices next to the app binary (`LICENSE.electron.txt`,',
    '`LICENSES.chromium.html`).',
    '',
    '## Fonts',
    '',
    '### JetBrains Mono (as patched by Nerd Fonts) — OFL-1.1',
    '',
    'Bundled as `JetBrainsMonoNerdFontMono-*.woff2`.',
    '',
    fence(readFileSync(join(fonts, 'OFL.txt'), 'utf8').trim()),
    '',
    '### Nerd Fonts patch and glyph sets',
    '',
    fence(readFileSync(join(fonts, 'LICENSE-NerdFonts.txt'), 'utf8').trim()),
    '',
    `## npm packages (${entries.length})`,
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...entries.map((e) => `| ${e.name} | ${e.version} | ${e.license} |`),
    ''
  ]
  for (const e of entries) {
    out.push(`### ${e.name}@${e.version} — ${e.license}`, '')
    if (e.repo) out.push(e.repo, '')
    out.push(
      e.text ? fence(e.text) : `_No license file in the package; declared license: ${e.license}._`,
      ''
    )
  }
  return out.join('\n')
}

const entries = collect()
writeFileSync(join(ROOT, 'THIRD-PARTY-NOTICES.md'), render(entries))
const unknown = entries.filter((e) => e.license === 'UNKNOWN')
console.log(
  `wrote THIRD-PARTY-NOTICES.md: ${entries.length} packages, ${unknown.length} without a declared license`
)
for (const e of unknown) console.log(`  ! ${e.name}@${e.version}`)
